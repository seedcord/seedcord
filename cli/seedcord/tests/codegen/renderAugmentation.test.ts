describe('renderAugmentation plugin capabilities', () => {
    const empty = { slash: {}, userContextMenus: {}, messageContextMenus: {}, emojis: {} };

    it('imports the bot and augments Core with one member per attach key', () => {
        const output = renderAugmentation(empty, AUGMENT_TARGET, { specifier: './bot', keys: ['db', 'cache'] });

        expect(output).toBe(
            `// Generated by \`seedcord codegen\`. Do not edit by hand.
// Run \`seedcord codegen\` after changing your commands, plugins, or emoji config.

import type Bot from './bot';

// prettier-ignore
declare module '@seedcord/gateway' {
    interface Core {
        cache: (typeof Bot)['cache'];
        db: (typeof Bot)['db'];
    }
    interface SlashRegistry {

    }
    interface UserContextMenuRegistry {

    }
    interface MessageContextMenuRegistry {

    }
    interface EmojiMap {

    }
}

export {};
`
        );
    });

    it('emits no import and no Core block for a bot with no plugins', () => {
        const output = renderAugmentation(empty, AUGMENT_TARGET, { specifier: './bot', keys: [] });

        expect(output).toBe(renderAugmentation(empty, AUGMENT_TARGET));
        expect(output).not.toContain('import type');
        expect(output).not.toContain('interface Core');
    });

    it('is byte-stable across attach-key order', () => {
        const first = renderAugmentation(empty, AUGMENT_TARGET, { specifier: './bot', keys: ['db', 'cache'] });
        const second = renderAugmentation(empty, AUGMENT_TARGET, { specifier: './bot', keys: ['cache', 'db'] });

        expect(first).toBe(second);
    });

    it('quotes an attach key that is not a valid identifier', () => {
        const output = renderAugmentation(empty, AUGMENT_TARGET, { specifier: './bot', keys: ['my-db'] });

        expect(output).toContain("        'my-db': (typeof Bot)['my-db'];");
    });

    it('escapes an apostrophe in an attach key', () => {
        const output = renderAugmentation(empty, AUGMENT_TARGET, { specifier: './bot', keys: ["tony's"] });

        expect(output).toContain(String.raw`        'tony\'s': (typeof Bot)['tony\'s'];`);
    });

    it('carries the specifier through unchanged', () => {
        const output = renderAugmentation(empty, AUGMENT_TARGET, { specifier: '../src/bot', keys: ['db'] });

        expect(output).toContain("import type Bot from '../src/bot';");
    });

    it('escapes an apostrophe in the bot specifier', () => {
        const output = renderAugmentation(empty, AUGMENT_TARGET, { specifier: "./tony's/bot", keys: ['db'] });

        expect(output).toContain(String.raw`import type Bot from './tony\'s/bot';`);
    });

    it('escapes a backslash in the bot specifier', () => {
        const output = renderAugmentation(empty, AUGMENT_TARGET, { specifier: String.raw`./a\b/bot`, keys: ['db'] });

        expect(output).toContain(String.raw`import type Bot from './a\\b/bot';`);
    });
});

describe('renderAugmentation emoji rows', () => {
    it('renders emoji keys into EmojiMap, application for a string config and guild for a tuple config', () => {
        const output = renderSlashWith({
            slash: {},
            userContextMenus: {},
            messageContextMenus: {},
            emojis: { Confirm: 'string', Lol: 'tuple', Cancel: 'string' }
        });

        expect(output).toContain(
            "    interface EmojiMap {\n        Cancel: 'application';\n        Confirm: 'application';\n        Lol: 'guild';\n    }"
        );
    });

    it('quotes an emoji key that is not a valid identifier', () => {
        const output = renderSlashWith({
            slash: {},
            userContextMenus: {},
            messageContextMenus: {},
            emojis: { 'thumbs-up': 'string' }
        });

        expect(output).toContain("        'thumbs-up': 'application';");
    });

    it('escapes an apostrophe in an emoji key', () => {
        const output = renderSlashWith({
            slash: {},
            userContextMenus: {},
            messageContextMenus: {},
            emojis: { "Tony's": 'string' }
        });

        expect(output).toContain(String.raw`        'Tony\'s': 'application';`);
    });

    it('is byte-stable across input order for the emoji keys', () => {
        const first = renderSlashWith({
            slash: {},
            userContextMenus: {},
            messageContextMenus: {},
            emojis: { Confirm: 'string', Lol: 'tuple' }
        });
        const second = renderSlashWith({
            slash: {},
            userContextMenus: {},
            messageContextMenus: {},
            emojis: { Lol: 'tuple', Confirm: 'string' }
        });

        expect(first).toBe(second);
    });
});

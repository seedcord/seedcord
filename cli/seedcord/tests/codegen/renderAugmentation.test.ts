import { ChannelType } from 'discord-api-types/v10';
import { describe, it, expect } from 'vitest';

import { renderAugmentation } from '#commands/codegen/renderAugmentation';

import type { RouteOptions, SlashTables } from '#commands/codegen/AugmentationBuilder';

const AUGMENT_TARGET = '@seedcord/gateway';

function renderWithTarget(registry: Parameters<typeof renderAugmentation>[0]): string {
    return renderAugmentation(registry, AUGMENT_TARGET);
}

// most assertions only exercise the option tables, so wrap each route as a guild-only row
function guildRows(tables: Record<string, RouteOptions>): SlashTables {
    return Object.fromEntries(
        Object.entries(tables).map(([route, options]) => [route, { options, cache: 'cached' as const }])
    );
}

function renderSlash(tables: Record<string, RouteOptions>): string {
    return renderWithTarget({ slash: guildRows(tables), userContextMenus: {}, messageContextMenus: {}, emojis: {} });
}

type FlatRegistry = Omit<Parameters<typeof renderAugmentation>[0], 'slash'> & { slash: Record<string, RouteOptions> };

function renderSlashWith(registry: FlatRegistry, plugins?: Parameters<typeof renderAugmentation>[2]): string {
    return renderAugmentation({ ...registry, slash: guildRows(registry.slash) }, AUGMENT_TARGET, plugins);
}

describe('prettier shield', () => {
    it('shields the declare-module block from the consumer repo prettier', () => {
        const output = renderSlash({});
        expect(output).toContain("// prettier-ignore\ndeclare module '@seedcord/gateway' {");
    });
});

